package com.siprikorea.crypto.engines;

import org.bouncycastle.crypto.BlockCipher;
import org.bouncycastle.crypto.CipherParameters;
import org.bouncycastle.crypto.DataLengthException;
import org.bouncycastle.crypto.OutputLengthException;
import org.bouncycastle.crypto.params.KeyParameter;
import org.bouncycastle.util.Arrays;

/**
 * HIGHT block cipher (TTAS.KO-12.0040/R1, ISO/IEC 18033-3:2010) - a 64-bit block cipher with a
 * 128-bit key and 32 rounds, designed for low-resource environments.
 * <p>
 * The round functions F0 and F1 are computed with rotations rather than looked up in 256-entry
 * tables, so that no memory access depends on secret data.
 * </p>
 */
public class HIGHTEngine
    implements BlockCipher
{
    private static final int BLOCK_SIZE = 8;
    private static final int KEY_SIZE = 16;
    private static final int ROUNDS = 32;

    // delta_i, generated by the LFSR s(i+7) = s(i+3) xor s(i), delta_0 = 0x5A
    private static final byte[] DELTA = new byte[128];

    static
    {
        int d = 0x5A;
        for (int i = 0; i < 128; ++i)
        {
            DELTA[i] = (byte)d;
            d = (d >>> 1) | ((((d) ^ (d >>> 3)) & 1) << 6);
        }
    }

    private byte[] rk;
    private boolean forEncryption;

    public void init(boolean forEncryption, CipherParameters params)
    {
        if (!(params instanceof KeyParameter))
        {
            throw new IllegalArgumentException("invalid parameter passed to HIGHT init - "
                + (params == null ? "null" : params.getClass().getName()));
        }

        byte[] key = ((KeyParameter)params).getKey();
        if (key.length != KEY_SIZE)
        {
            throw new IllegalArgumentException("HIGHT key must be 128 bits");
        }

        this.forEncryption = forEncryption;
        this.rk = generateRoundKeys(key);
    }

    public String getAlgorithmName()
    {
        return "HIGHT";
    }

    public int getBlockSize()
    {
        return BLOCK_SIZE;
    }

    public int processBlock(byte[] in, int inOff, byte[] out, int outOff)
    {
        if (rk == null)
        {
            throw new IllegalStateException("HIGHT engine not initialised");
        }
        if (inOff > in.length - BLOCK_SIZE)
        {
            throw new DataLengthException("input buffer too short");
        }
        if (outOff > out.length - BLOCK_SIZE)
        {
            throw new OutputLengthException("output buffer too short");
        }

        if (forEncryption)
        {
            encryptBlock(in, inOff, out, outOff);
        }
        else
        {
            decryptBlock(in, inOff, out, outOff);
        }

        return BLOCK_SIZE;
    }

    public void reset()
    {
    }

    /*
     * rk[0..7] are the whitening keys WK0..WK7, rk[8..135] the subkeys SK0..SK127.
     */
    private static byte[] generateRoundKeys(byte[] mk)
    {
        byte[] rk = new byte[8 + 4 * ROUNDS];

        for (int i = 0; i < 4; ++i)
        {
            rk[i] = mk[i + 12];
            rk[i + 4] = mk[i];
        }

        for (int i = 0; i < 8; ++i)
        {
            for (int j = 0; j < 8; ++j)
            {
                rk[8 + 16 * i + j] = (byte)(mk[(j - i) & 7] + DELTA[16 * i + j]);
                rk[8 + 16 * i + j + 8] = (byte)(mk[((j - i) & 7) + 8] + DELTA[16 * i + j + 8]);
            }
        }

        return rk;
    }

    private static int f0(int x)
    {
        return (rotl8(x, 1) ^ rotl8(x, 2) ^ rotl8(x, 7)) & 0xFF;
    }

    private static int f1(int x)
    {
        return (rotl8(x, 3) ^ rotl8(x, 4) ^ rotl8(x, 6)) & 0xFF;
    }

    private static int rotl8(int x, int n)
    {
        return ((x << n) | (x >>> (8 - n))) & 0xFF;
    }

    private void encryptBlock(byte[] in, int inOff, byte[] out, int outOff)
    {
        int[] x = new int[8];

        x[1] = in[inOff + 1] & 0xFF;
        x[3] = in[inOff + 3] & 0xFF;
        x[5] = in[inOff + 5] & 0xFF;
        x[7] = in[inOff + 7] & 0xFF;
        x[0] = (in[inOff] + rk[0]) & 0xFF;
        x[2] = (in[inOff + 2] ^ rk[1]) & 0xFF;
        x[4] = (in[inOff + 4] + rk[2]) & 0xFF;
        x[6] = (in[inOff + 6] ^ rk[3]) & 0xFF;

        for (int k = 2; k < ROUNDS + 2; ++k)
        {
            int r = k - 2;
            int i0 = (7 - r) & 7, i1 = (6 - r) & 7, i2 = (5 - r) & 7, i3 = (4 - r) & 7;
            int i4 = (3 - r) & 7, i5 = (2 - r) & 7, i6 = (1 - r) & 7, i7 = (0 - r) & 7;

            x[i0] = (x[i0] ^ (f0(x[i1]) + (rk[4 * k + 3] & 0xFF))) & 0xFF;
            x[i2] = (x[i2] + (f1(x[i3]) ^ (rk[4 * k + 2] & 0xFF))) & 0xFF;
            x[i4] = (x[i4] ^ (f0(x[i5]) + (rk[4 * k + 1] & 0xFF))) & 0xFF;
            x[i6] = (x[i6] + (f1(x[i7]) ^ (rk[4 * k] & 0xFF))) & 0xFF;
        }

        out[outOff + 1] = (byte)x[2];
        out[outOff + 3] = (byte)x[4];
        out[outOff + 5] = (byte)x[6];
        out[outOff + 7] = (byte)x[0];
        out[outOff] = (byte)(x[1] + rk[4]);
        out[outOff + 2] = (byte)(x[3] ^ rk[5]);
        out[outOff + 4] = (byte)(x[5] + rk[6]);
        out[outOff + 6] = (byte)(x[7] ^ rk[7]);

        Arrays.fill(x, 0);
    }

    private void decryptBlock(byte[] in, int inOff, byte[] out, int outOff)
    {
        int[] x = new int[8];

        x[2] = in[inOff + 1] & 0xFF;
        x[4] = in[inOff + 3] & 0xFF;
        x[6] = in[inOff + 5] & 0xFF;
        x[0] = in[inOff + 7] & 0xFF;
        x[1] = (in[inOff] - rk[4]) & 0xFF;
        x[3] = (in[inOff + 2] ^ rk[5]) & 0xFF;
        x[5] = (in[inOff + 4] - rk[6]) & 0xFF;
        x[7] = (in[inOff + 6] ^ rk[7]) & 0xFF;

        for (int k = ROUNDS + 1; k >= 2; --k)
        {
            int r = (ROUNDS + 1) - k;
            int i0 = (7 + r) & 7, i1 = (6 + r) & 7, i2 = (5 + r) & 7, i3 = (4 + r) & 7;
            int i4 = (3 + r) & 7, i5 = (2 + r) & 7, i6 = (1 + r) & 7, i7 = r & 7;

            x[i1] = (x[i1] - (f1(x[i2]) ^ (rk[4 * k + 2] & 0xFF))) & 0xFF;
            x[i3] = (x[i3] ^ (f0(x[i4]) + (rk[4 * k + 1] & 0xFF))) & 0xFF;
            x[i5] = (x[i5] - (f1(x[i6]) ^ (rk[4 * k] & 0xFF))) & 0xFF;
            x[i7] = (x[i7] ^ (f0(x[i0]) + (rk[4 * k + 3] & 0xFF))) & 0xFF;
        }

        out[outOff + 1] = (byte)x[1];
        out[outOff + 3] = (byte)x[3];
        out[outOff + 5] = (byte)x[5];
        out[outOff + 7] = (byte)x[7];
        out[outOff] = (byte)(x[0] - rk[0]);
        out[outOff + 2] = (byte)(x[2] ^ rk[1]);
        out[outOff + 4] = (byte)(x[4] - rk[2]);
        out[outOff + 6] = (byte)(x[6] ^ rk[3]);

        Arrays.fill(x, 0);
    }
}
